class TestCanonicalJSON:
    """Test that canonical JSON output matches Go implementation."""

    def test_sorted_keys(self, vectors):
        test = vectors["canonical_json"][0]
        result = pact.canonical_json(test["input"])
        assert result.decode("utf-8") == test["output"]

    def test_nested_objects(self, vectors):
        test = vectors["canonical_json"][1]
        result = pact.canonical_json(test["input"])
        assert result.decode("utf-8") == test["output"]


class TestCapabilityNarrowing:
    """Test that capability matching matches Go implementation."""

    def test_all_narrowing_vectors(self, vectors):
        for case in vectors["capability_narrowing"]:
            parent = pact.parse_capability(case["parent"])
            child = pact.parse_capability(case["child"])
            result = parent.covers(child)
            assert result == case["covers"], (
                f"parent={case['parent']}, child={case['child']}: "
                f"expected covers={case['covers']}, got {result}"
            )


class TestContentDigest:
    """Test that content digest matches Go implementation."""

    def test_all_digest_vectors(self, vectors):
        for case in vectors["content_digest"]:
            body = case["body"].encode("utf-8")
            digest = pact.compute_content_digest(body)
            assert digest == case["digest"], (
                f"body={case['body']!r}: expected {case['digest']}, got {digest}"
            )


class TestDelegationSigning:
    """Test that delegation signatures match Go implementation."""

    def test_canonical_payload(self, vectors):
        """Verify the canonical JSON payload matches byte-for-byte."""
        deleg_data = vectors["delegation"]

        # Create Alice and Bob with deterministic seeds
        alice = pact.identity_from_seed(
            pact.test_vector_seed("alice"), "human", "Alice")
        bob = pact.identity_from_seed(pact.test_vector_seed(
            "bob-agent"), "agent", "Bob's Agent")

        # Build a delegation manually (matching test vector fields exactly)
        d = pact.Delegation(
            type="delegation",
            version="1.0",
            id="d-testvector-0001",
            from_entity=pact.DelegationEntity(
                type="human",
                id=alice.id,
                public_key=alice.public_key,
                name="Alice",
            ),
            to_entity=pact.DelegationEntity(
                type="agent",
                id=bob.id,
                public_key=bob.public_key,
                name="Bob's Agent",
            ),
            capabilities=["repo:read,repo=myorg/*",
                          "deploy:create,env=staging"],
            constraints=pact.DelegationConstraints(
                expires="2099-01-01T00:00:00Z",
                max_chain_depth=2,
                not_before="2025-01-01T00:00:00Z",
            ),
            issued_at="2025-01-01T00:00:00Z",
            signature="",
        )

        # Get the canonical payload
        payload = d.signing_payload()
        payload_str = payload.decode("utf-8")

        assert payload_str == deleg_data["canonical_payload"], (
            f"Canonical payload mismatch.\n"
            f"Expected: {deleg_data['canonical_payload']}\n"
            f"Got:      {payload_str}"
        )

