"""Cross-language test vector validation.

Validates the Python SDK against the reference test vectors in testdata/vectors.json.
These vectors were generated by the Go implementation using deterministic Ed25519 keys.

If these tests pass, the Python implementation is byte-compatible with Go.
"""

import pact
import json
import os
from pathlib import Path

import pytest

# Add parent to path for imports
import sys
sys.path.insert(0, str(Path(__file__).parent.parent))


# Load test vectors
VECTORS_PATH = Path(__file__).parent.parent.parent.parent / \
    "testdata" / "vectors.json"


@pytest.fixture(scope="module")
def vectors():
    with open(VECTORS_PATH) as f:
        return json.load(f)


class TestSeedDerivation:
    """Test that seed derivation matches Go implementation."""

    def test_alice_seed(self, vectors):
        seed = pact.test_vector_seed("alice")
