    def test_delegation_signature(self, vectors):
        """Verify the Ed25519 signature matches Go implementation."""
        deleg_data = vectors["delegation"]
        signed = deleg_data["signed_delegation"]

        alice = pact.identity_from_seed(
            pact.test_vector_seed("alice"), "human", "Alice")
        bob = pact.identity_from_seed(pact.test_vector_seed(
            "bob-agent"), "agent", "Bob's Agent")

        d = pact.Delegation(
            type="delegation",
            version="1.0",
            id="d-testvector-0001",
            from_entity=pact.DelegationEntity(
                type="human",
                id=alice.id,
                public_key=alice.public_key,
                name="Alice",
            ),
            to_entity=pact.DelegationEntity(
                type="agent",
                id=bob.id,
                public_key=bob.public_key,
                name="Bob's Agent",
            ),
            capabilities=["repo:read,repo=myorg/*",
                          "deploy:create,env=staging"],
            constraints=pact.DelegationConstraints(
                expires="2099-01-01T00:00:00Z",
                max_chain_depth=2,
                not_before="2025-01-01T00:00:00Z",
            ),
            issued_at="2025-01-01T00:00:00Z",
            signature="",
        )

        # Sign with Alice's key
        d._sign(alice)

        assert d.signature == signed["signature"], (
            f"Signature mismatch.\n"
            f"Expected: {signed['signature']}\n"
            f"Got:      {d.signature}"
        )

    def test_signed_delegation_verifies(self, vectors):
        """Verify the Go-generated signature can be verified by Python."""
        signed = vectors["delegation"]["signed_delegation"]

        # Reconstruct alice's public key
        alice = pact.identity_from_seed(
            pact.test_vector_seed("alice"), "human", "Alice")

        # Build delegation from the signed test vector
        d = pact.Delegation.from_dict(signed)

        # Verify: set signature to "", canonicalize, verify with alice's pub key
        payload = d.signing_payload()
        sig_bytes = pact.decode_base64url(signed["signature"])

        assert alice.verify(payload, sig_bytes)
